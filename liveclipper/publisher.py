#!/usr/bin/env python3
"""publisher.py - upload clips to YOUR OWN YouTube channel (official YouTube Data API), by hand or on autopilot.

Everything here runs on this computer. Safety rules built in:
  * autopilot is OFF until you turn it on in the web UI, and turning it on needs a rights confirmation
  * default privacy is PRIVATE; you pick unlisted/public yourself
  * a rejected clip is never uploaded; every clip is uploaded at most once (3 tries on errors)
  * every attempt is written to watch_data/uploads.jsonl (what, where, when, result)
  * client_secret.json and the login token stay on this computer (token is chmod 600) and are never inside the repo
"""
import json, os, threading, time
from pathlib import Path

CONFIG_DIR = Path.home() / ".config" / "liveclipper"
TOKEN = CONFIG_DIR / "youtube_token.json"
SCOPES = ["https://www.googleapis.com/auth/youtube.upload"]
PLATFORMS = ("youtube", "facebook", "instagram", "tiktok")
MODES = ("off", "approved", "all")
PRIVACY = ("private", "unlisted", "public")
MAX_TRIES = 3


def secret_path():
    for p in (CONFIG_DIR / "client_secret.json", Path("client_secret.json")):
        if p.is_file():
            return p
    return None


class Settings:
    def __init__(self, home):
        self.path = Path(home) / "settings.json"
        self.lock = threading.Lock()

    def get(self):
        d = dict(autopilot="off", privacy="private", rights_ack=None, targets=["youtube"])
        try:
            d.update(json.loads(self.path.read_text()))
        except (OSError, ValueError):
            pass
        return d

    def update(self, autopilot=None, privacy=None, rights_ack=None, targets=None):
        with self.lock:
            d = self.get()
            if privacy is not None:
                if privacy not in PRIVACY:
                    raise ValueError("bad privacy")
                d["privacy"] = privacy
            if targets is not None:
                if not isinstance(targets, list) or not all(t in PLATFORMS for t in targets):
                    raise ValueError("bad targets")
                d["targets"] = list(dict.fromkeys(targets))
            if rights_ack is not None:
                d["rights_ack"] = time.strftime("%Y-%m-%d %H:%M:%S") if rights_ack else None
            if autopilot is not None:
                if autopilot not in MODES:
                    raise ValueError("bad autopilot mode")
                if autopilot != "off" and not d.get("rights_ack"):
                    raise ValueError("tick the rights confirmation first: autopilot publishes as you")
                d["autopilot"] = autopilot
            if d["autopilot"] != "off" and not d.get("rights_ack"):
                d["autopilot"] = "off"
            self.path.parent.mkdir(parents=True, exist_ok=True)
            tmp = self.path.with_suffix(".tmp")
            tmp.write_text(json.dumps(d, indent=2))
            tmp.replace(self.path)
            return d


class UploadLog:
    def __init__(self, home):
        self.path = Path(home) / "uploads.jsonl"
        self.lock = threading.Lock()

    def add(self, **rec):
        rec["at"] = time.strftime("%Y-%m-%d %H:%M:%S")
        with self.lock:
            self.path.parent.mkdir(parents=True, exist_ok=True)
            with open(self.path, "a") as f:
                f.write(json.dumps(rec) + "\n")

    def all(self):
        try:
            return [json.loads(l) for l in self.path.read_text().splitlines() if l.strip()]
        except (OSError, ValueError):
            return []

    def done(self, clip_id, platform="youtube"):
        return any(r.get("clip") == clip_id and r.get("platform") == platform and r.get("status") == "uploaded" for r in self.all())

    def tries(self, clip_id, platform="youtube"):
        return sum(1 for r in self.all() if r.get("clip") == clip_id and r.get("platform") == platform and r.get("status") == "failed")


def build_pack(mp4, meta_hint=None, store=None, clip_id=None, make_thumb=True):
    """Title/description/tags/caption/thumbnail for a clip: your saved edits, else generated by metadata.py.
    The file name is never used as a title."""
    import metadata
    mp4 = Path(mp4)
    old = {}
    if mp4.name.endswith("_final.mp4"):
        up = mp4.with_name(mp4.name[:-len("_final.mp4")] + "_upload.json")
        if up.exists():
            try:
                old = json.loads(up.read_text())
            except ValueError:
                old = {}
    hint = meta_hint or {}
    cid = clip_id or hint.get("id") or mp4.name
    game = store.game() if store else metadata.DEFAULT_GAME
    gen = metadata.generate(mp4, hint, old, game=game, clip_id=cid)
    ed = store.edits(cid) if store else {}
    pack = {k: (ed[k] if k in ed and ed[k] not in ("", []) else gen[k]) for k in ("title", "description", "tags", "caption", "headline")}
    pack["title"] = pack["title"][:100]
    pack["description"] = pack["description"][:5000]
    pack["tags"] = list(pack["tags"])[:30]
    pack["hashtags"] = gen["hashtags"]
    if "title" in ed and "caption" not in ed:
        pack["caption"] = (pack["title"] + "\n\n" + " ".join("#" + h for h in gen["hashtags"][:6]))[:2200]
    thumb = None
    if make_thumb:
        thumb = metadata.ensure_thumbnail(mp4, hint, pack["headline"])
    pack["thumbnail"] = thumb
    pack["edited"] = bool(ed)
    return pack


def credentials(interactive=False):
    from google.oauth2.credentials import Credentials
    from google.auth.transport.requests import Request
    creds = Credentials.from_authorized_user_file(str(TOKEN), SCOPES) if TOKEN.exists() else None
    if creds and creds.expired and creds.refresh_token:
        creds.refresh(Request())
        _save(creds)
    if creds and creds.valid:
        return creds
    if not interactive:
        raise RuntimeError("YouTube is not connected yet: click Connect YouTube in the Upload tab")
    sp = secret_path()
    if not sp:
        raise RuntimeError("client_secret.json not found (put it in ~/.config/liveclipper/)")
    from google_auth_oauthlib.flow import InstalledAppFlow
    creds = InstalledAppFlow.from_client_secrets_file(str(sp), SCOPES).run_local_server(port=0)
    _save(creds)
    return creds


def _save(creds):
    CONFIG_DIR.mkdir(parents=True, exist_ok=True, mode=0o700)
    fd = os.open(str(TOKEN), os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(creds.to_json())
    os.chmod(TOKEN, 0o600)


def youtube_upload(video, pack, privacy):
    """Real upload. Returns the video URL. Raises on any API error."""
    from googleapiclient.discovery import build
    from googleapiclient.http import MediaFileUpload
    yt = build("youtube", "v3", credentials=credentials(), cache_discovery=False)
    body = {"snippet": {"title": pack["title"], "description": pack["description"], "tags": pack["tags"], "categoryId": "20"},
            "status": {"privacyStatus": privacy, "selfDeclaredMadeForKids": False}}
    req = yt.videos().insert(part="snippet,status", body=body, media_body=MediaFileUpload(str(video), chunksize=-1, resumable=True))
    resp = None
    while resp is None:
        _, resp = req.next_chunk()
    url = "https://youtu.be/" + resp["id"]
    if pack.get("thumbnail"):
        try:
            yt.thumbnails().set(videoId=resp["id"], media_body=MediaFileUpload(str(pack["thumbnail"]))).execute()
        except Exception as e:  # channel may need phone verification for custom thumbnails; the video is already up
            url += "  (thumbnail not set: %s)" % str(e)[:120]
    return url


class Publisher:
    def __init__(self, home, uploader=youtube_upload, extra=None):
        self.settings, self.log = Settings(home), UploadLog(home)
        self.uploaders = dict(youtube=uploader)
        if extra is None:
            import platforms
            extra = platforms.UPLOADERS
        self.uploaders.update(extra)
        self.busy = threading.Lock()
        import metadata
        self.meta = metadata.MetaStore(home)

    def connected(self, platform):
        if platform == "youtube":
            return TOKEN.exists()
        import platforms
        return platforms.status().get(platform, False)

    def upload(self, clip_id, mp4, decision, meta_hint=None, source="manual", privacy=None, platform="youtube"):
        """Upload one clip to one platform. Refuses rejected clips and repeats. Logs the outcome."""
        if platform not in self.uploaders:
            raise ValueError("unknown platform")
        if decision == "rejected":
            raise ValueError("this clip was rejected")
        if self.log.done(clip_id, platform):
            raise ValueError("already uploaded to " + platform)
        mp4 = Path(mp4)
        if not mp4.is_file():
            raise ValueError("clip file not found")
        privacy = privacy or self.settings.get()["privacy"]
        if privacy not in PRIVACY:
            raise ValueError("bad privacy")
        pack = build_pack(mp4, meta_hint, self.meta, clip_id)
        with self.busy:
            try:
                url = self.uploaders[platform](mp4, pack, privacy)
            except Exception as e:
                self.log.add(clip=clip_id, platform=platform, status="failed", title=pack["title"], privacy=privacy, by=source, error=str(e)[:300])
                raise RuntimeError(f"{platform}: {str(e)[:300]}")
        self.log.add(clip=clip_id, platform=platform, status="uploaded", title=pack["title"], privacy=privacy, by=source, url=url)
        return url

    def upload_targets(self, clip_id, mp4, decision, meta_hint=None, source="manual", privacy=None):
        """Upload to every selected platform that is connected. -> {platform: url or 'error: ...'}"""
        out = {}
        for pl in self.settings.get()["targets"]:
            if self.log.done(clip_id, pl):
                continue
            if not self.connected(pl):
                out[pl] = "error: not connected"
                continue
            try:
                out[pl] = self.upload(clip_id, mp4, decision, meta_hint, source, privacy, pl)
            except Exception as e:
                out[pl] = "error: " + str(e)
        return out

    def eligible(self, clips):
        """[(clip, platform)] that autopilot would upload now."""
        st = self.settings.get()
        mode, out = st["autopilot"], []
        for c in clips:
            if mode == "off" or c["review"] == "rejected":
                continue
            if mode == "approved" and c["review"] != "approved":
                continue
            for pl in st["targets"]:
                if self.log.done(c["id"], pl) or self.log.tries(c["id"], pl) >= MAX_TRIES or not self.connected(pl):
                    continue
                out.append((c, pl))
        return out

    def autopilot_pass(self, clips, resolve):
        """Upload every eligible clip to every selected, connected platform (one at a time). Returns the number attempted."""
        n = 0
        for c, pl in self.eligible(clips):
            if self.settings.get()["autopilot"] == "off":
                break
            n += 1
            try:
                self.upload(c["id"], resolve(c["id"]), c["review"], c, source="autopilot", platform=pl)
            except Exception:
                pass  # already logged as failed
        return n
